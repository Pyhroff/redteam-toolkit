"""
recon/waf_detector.py — WAF fingerprinter + bypass technique suggester

WHY most scanners fail against real targets:
  Before you fuzz a web app, you NEED to know if a WAF (Web Application
  Firewall) is in front of it. Running sqlmap or a dir fuzzer blindly
  against Cloudflare or ModSecurity will get you blocked and generate
  noise without yielding results.

WHAT THIS DOES:
  1. PASSIVE DETECTION — inspects HTTP response headers, cookies, error pages
  2. ACTIVE DETECTION  — sends crafted attack payloads and watches the reaction
     (rate-limit? IP block? Custom error page? Modified response?)
  3. FINGERPRINTING    — maps detected patterns to specific WAF vendors
  4. BYPASS SUGGESTIONS — for each identified WAF, lists known bypass techniques

KILL CHAIN PHASE: Reconnaissance (pre-exploitation intelligence)

USAGE:
  python recon/waf_detector.py -u http://target.com
  python recon/waf_detector.py -u http://target.com --active
  python recon/waf_detector.py -u http://target.com --active --verbose

ONLY use on systems you own or have written permission to test.
REQUIRES: pip install requests
"""

